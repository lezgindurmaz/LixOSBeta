/* ---- Set VGA mode via BIOS INT 10h ---- */
void vga_setmode(int mode) {
    union REGS r;
    r.x.ax = mode;
    int86(0x10, &r, &r);
}

/* ---- Upload our custom palette ---- */
void vga_setpalette(void) {
    /* Port-based palette write: 3C8h = index, 3C9h = R,G,B (6-bit each) */
    static const unsigned char pal[][3] = {
        /* 0-15: standard CGA colors */
        {0,0,0},{0,0,42},{0,42,0},{0,42,42},
        {42,0,0},{42,0,42},{42,21,0},{42,42,42},
        {21,21,21},{21,21,63},{21,63,21},{21,63,63},
        {63,21,21},{63,21,63},{63,63,21},{63,63,63},
        /* 16: Win title blue    */ {0,0,42},
        /* 17: Win gray bg       */ {48,48,48},
        /* 18: Win dark border   */ {0,0,0},
        /* 19: Win light border  */ {63,63,63},
        /* 20: Desktop teal      */ {0,32,32},
        /* 21: Button face       */ {48,48,48},
        /* 22: Button shadow     */ {16,16,16},
        /* 23: Button highlight  */ {63,63,63},
        /* 24: Title text white  */ {63,63,63},
        /* 25: Menu background   */ {55,55,55},
        /* 26: Notepad blue bg   */ {0,0,42},
        /* 27: Notepad text      */ {63,63,63},
    };
    int i;
    outportb(0x3C8, 0);
    for(i = 0; i < 28; i++) {
        outportb(0x3C9, pal[i][0]);
        outportb(0x3C9, pal[i][1]);
        outportb(0x3C9, pal[i][2]);
    }
}

/* ---- Init: set mode 13h, upload palette ---- */
void vga_init(void) {
    __djgpp_nearptr_enable();
    vga_setmode(0x13);
    vga_setpalette();
    memset(vga_buffer, COL_DESKTOP, sizeof(vga_buffer));
}

/* ---- Blit double buffer to VGA memory ---- */
void vga_flip(void) {
    memcpy((unsigned char *)VGA_MEM, vga_buffer, SCREEN_W * SCREEN_H);
}

void vga_clear(unsigned char color) {
    memset(vga_buffer, color, SCREEN_W * SCREEN_H);
}

void vga_putpixel(int x, int y, unsigned char color) {
    if(x >= 0 && x < SCREEN_W && y >= 0 && y < SCREEN_H)
        vga_buffer[y][x] = color;
}

void vga_hline(int x1, int x2, int y, unsigned char color) {
    int x;
    if(y < 0 || y >= SCREEN_H) return;
    if(x1 > x2) { int t=x1; x1=x2; x2=t; }
    if(x1 < 0) x1=0;
    if(x2 >= SCREEN_W) x2=SCREEN_W-1;
    for(x=x1; x<=x2; x++) vga_buffer[y][x]=color;
}

void vga_vline(int x, int y1, int y2, unsigned char color) {
    int y;
    if(x < 0 || x >= SCREEN_W) return;
    if(y1 > y2) { int t=y1; y1=y2; y2=t; }
    if(y1 < 0) y1=0;
    if(y2 >= SCREEN_H) y2=SCREEN_H-1;
    for(y=y1; y<=y2; y++) vga_buffer[y][x]=color;
}

void vga_rect(int x, int y, int w, int h, unsigned char color) {
    vga_hline(x, x+w-1, y,     color);
    vga_hline(x, x+w-1, y+h-1, color);
    vga_vline(x,     y, y+h-1, color);
    vga_vline(x+w-1, y, y+h-1, color);
}

void vga_fillrect(int x, int y, int w, int h, unsigned char color) {
    int r;
    int ex = x+w, ey = y+h;
    if(x < 0) x=0; if(y < 0) y=0;
    if(ex > SCREEN_W) ex=SCREEN_W;
    if(ey > SCREEN_H) ey=SCREEN_H;
    for(r=y; r<ey; r++)
        memset(&vga_buffer[r][x], color, ex-x);
}

/* ---- Draw one character from font ---- */
void vga_putchar(int x, int y, char c, unsigned char fg, unsigned char bg) {
    int row, col;
    unsigned char bits;
    int idx = (unsigned char)c - 32;
    if(idx < 0 || idx >= 95) idx = 0;
    for(row=0; row<8; row++) {
        bits = font8x8[idx][row];
        for(col=0; col<8; col++) {
            unsigned char color = (bits & (0x80>>col)) ? fg : bg;
            vga_putpixel(x+col, y+row, color);
        }
    }
}

void vga_putstr(int x, int y, const char *s, unsigned char fg, unsigned char bg) {
    while(*s) {
        vga_putchar(x, y, *s, fg, bg);
        x += 8;
        s++;
    }
}

int vga_strwidth(const char *s) {
    int n=0;
    while(*s++) n++;
    return n*8;
}
